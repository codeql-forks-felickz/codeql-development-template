require "openssl"
require "base64"
require "securerandom"

# Reduced from a deterministic token-encryption helper: a hard-coded IV
# constant (defined in constants.rb) is sliced and reused for every encryption.
module Encryption
  def self.encrypt_sensitive_value(val = "")
    aes = OpenSSL::Cipher.new(cipher_type)
    aes.encrypt
    aes.key = key[0..31]
    aes.iv = iv[0..15] if iv != nil # $ Alert
    new_val = aes.update("#{val}") + aes.final
    Base64.strict_encode64(new_val).encode("utf-8")
  end

  # Decrypting with the IV that was used for encryption is not itself a flaw.
  def self.decrypt_sensitive_value(val = "")
    aes = OpenSSL::Cipher.new(cipher_type)
    aes.decrypt
    aes.key = key[0..31]
    aes.iv = iv[0..15] if iv != nil
    decoded = Base64.strict_decode64("#{val}")
    aes.update("#{decoded}") + aes.final
  end

  def self.key
    ENV.fetch("APP_KEY")
  end

  def self.iv
    APP_IV
  end

  def self.cipher_type
    "aes-256-cbc"
  end
end

class StaticIvExamples
  def literal_iv(key, data)
    cipher = OpenSSL::Cipher::AES.new(256, :CBC)
    cipher.encrypt
    cipher.key = key
    cipher.iv = "0123456789abcdef" # $ Alert
    cipher.update(data) + cipher.final
  end

  def local_variable_iv(key, data)
    iv = "fedcba9876543210" # $ Source
    cipher = OpenSSL::Cipher.new("aes-128-gcm")
    cipher.encrypt
    cipher.key = key
    cipher.iv = iv # $ Alert
    cipher.update(data) + cipher.final
  end

  def zero_iv(key, data)
    cipher = OpenSSL::Cipher::AES256.new(:CBC)
    cipher.encrypt
    cipher.key = key
    cipher.iv = "\0" * 16 # $ Alert
    cipher.update(data) + cipher.final
  end

  # Mode not set explicitly: OpenSSL ciphers encrypt by default.
  def implicit_encrypt_mode(key, data)
    cipher = OpenSSL::Cipher.new("aes-256-cbc")
    cipher.key = key
    cipher.iv = "AAAAAAAAAAAAAAAA" # $ Alert
    cipher.update(data) + cipher.final
  end

  # Safe: IV generated by the cipher.
  def random_iv(key, data)
    cipher = OpenSSL::Cipher.new("aes-256-cbc")
    cipher.encrypt
    cipher.key = key
    iv = cipher.random_iv
    [iv, cipher.update(data) + cipher.final]
  end

  # Safe: IV from a CSPRNG.
  def secure_random_iv(key, data)
    cipher = OpenSSL::Cipher.new("aes-256-cbc")
    cipher.encrypt
    cipher.key = key
    iv = SecureRandom.random_bytes(16)
    cipher.iv = iv
    [iv, cipher.update(data) + cipher.final]
  end

  # Safe: IV loaded from configuration rather than hard-coded.
  def env_iv(key, data)
    cipher = OpenSSL::Cipher.new("aes-256-cbc")
    cipher.encrypt
    cipher.key = key
    cipher.iv = Base64.decode64(ENV["APP_IV"])
    cipher.update(data) + cipher.final
  end

  # Safe: decryption with an IV received alongside the ciphertext.
  def decrypt_with_iv(key, iv, data)
    cipher = OpenSSL::Cipher.new("aes-256-cbc")
    cipher.decrypt
    cipher.key = key
    cipher.iv = iv
    cipher.update(data) + cipher.final
  end

  # Safe: the static string is not the IV.
  def static_key_material_not_iv(data)
    cipher = OpenSSL::Cipher.new("aes-256-cbc")
    cipher.encrypt
    cipher.key = "k" * 32
    cipher.iv = cipher.random_iv
    cipher.update(data) + cipher.final
  end
end
