using Newtonsoft.Json.Linq;

namespace AspNetCoreApp
{
    public class UsersController : Controller
    {
        public IActionResult Import(string url)
        {
            string errorMsg = "Success";
            try
            {
                Fetch(url);
            }
            catch (Exception e)
            {
                errorMsg = e.Message; // $ Source
            }

            var json = new JObject(
                new JProperty("Error", errorMsg),
                new JProperty("Content", url)
            );
            return Ok(json); // $ Alert
        }

        public IActionResult ImportSafe(string url)
        {
            string errorMsg = "Success";
            try
            {
                Fetch(url);
            }
            catch (Exception)
            {
                // GOOD: generic message.
                errorMsg = "Import failed.";
            }

            return Ok(new JObject(new JProperty("Error", errorMsg)));
        }

        public IActionResult JsonError()
        {
            try
            {
                Fetch("x");
                return Json(new { error = "" });
            }
            catch (Exception e)
            {
                return Json(new { error = e.Message }); // $ Alert
            }
        }

        public string PlainText()
        {
            try
            {
                Fetch("x");
                return "ok";
            }
            catch (Exception e)
            {
                return e.Message; // $ Alert
            }
        }

        public IActionResult Error()
        {
            return View(new ErrorViewModel
            {
                RequestId = "id",
                ExceptionInfo = HttpContext.Features.Get<IExceptionHandlerPathFeature>(),
            });
        }

        // GOOD: not an action method.
        private string Describe(Exception e) => e.Message;

        private void Fetch(string url) { }
    }

