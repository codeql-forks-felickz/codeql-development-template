    public class ErrorViewModel
    {
        public string RequestId { get; set; }

        public IExceptionHandlerPathFeature ExceptionInfo { get; set; }
    }

    // Shape of the class generated by the Razor source generator for `Views/Shared/Error.cshtml`.
    public class Views_Shared_Error : RazorPage<ErrorViewModel>
    {
        public void ExecuteAsync()
        {
            WriteLiteral("<h4>Request id: ");
            Write(Model.RequestId);
            WriteLiteral("</h4><h4>Path: ");
            Write(Model.ExceptionInfo.Path);
            WriteLiteral("</h4><h4>Exception: ");
            Write(Model.ExceptionInfo.Error.Message); // $ Alert
            WriteLiteral("</h4><span>");
            Write(Model.ExceptionInfo.Error.StackTrace); // $ Alert
            WriteLiteral("</span>");
        }
